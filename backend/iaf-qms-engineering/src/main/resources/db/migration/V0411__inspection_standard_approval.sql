create table platform_approval_instance (
 id bigint generated by default as identity primary key, tenant_id bigint not null, org_id bigint not null,
 business_type varchar(64) not null, business_id bigint not null, approval_status varchar(32) not null,
 submitted_by bigint not null, submitted_at timestamp not null default current_timestamp,
 decided_by bigint, decided_at timestamp, decision_comment varchar(1000),
 created_by bigint, created_at timestamp not null default current_timestamp, updated_by bigint,
 updated_at timestamp not null default current_timestamp, deleted boolean not null default false,
 version int not null default 0, ext_json jsonb not null default '{}'
);
create index idx_platform_approval_business on platform_approval_instance(tenant_id,org_id,business_type,business_id,id desc);
create table platform_approval_action (
 id bigint generated by default as identity primary key, tenant_id bigint not null, org_id bigint not null,
 approval_instance_id bigint not null, action_code varchar(32) not null, actor_id bigint not null,
 comment varchar(1000), acted_at timestamp not null default current_timestamp,
 created_by bigint, created_at timestamp not null default current_timestamp, updated_by bigint,
 updated_at timestamp not null default current_timestamp, deleted boolean not null default false,
 version int not null default 0, ext_json jsonb not null default '{}',
 foreign key(approval_instance_id) references platform_approval_instance(id)
);
