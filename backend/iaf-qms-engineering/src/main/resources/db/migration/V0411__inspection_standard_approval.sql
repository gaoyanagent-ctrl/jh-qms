insert into sys_permission(tenant_id,permission_code,permission_name,resource_type,module_code,action_code,created_by,updated_by,deleted,version)
select t.id,p.code,p.name,'API','qms',p.action,0,0,false,0 from sys_tenant t cross join(values
 ('qms:inspection-standard:submit','Submit inspection standard','submit'),
 ('qms:inspection-standard:approve','Approve inspection standard','approve'),
 ('qms:inspection-standard:release','Release inspection standard','release'))p(code,name,action)
where t.deleted=false and not exists(select 1 from sys_permission x where x.tenant_id=t.id and x.permission_code=p.code and not x.deleted);
insert into sys_role_permission(tenant_id,role_id,permission_id,created_by,updated_by,deleted,version)
select r.tenant_id,r.id,p.id,0,0,false,0 from sys_role r join sys_permission p on p.tenant_id=r.tenant_id
where r.role_code='platform_admin' and not r.deleted and p.permission_code in('qms:inspection-standard:submit','qms:inspection-standard:approve','qms:inspection-standard:release') and not p.deleted
on conflict(tenant_id,role_id,permission_id) do nothing;
