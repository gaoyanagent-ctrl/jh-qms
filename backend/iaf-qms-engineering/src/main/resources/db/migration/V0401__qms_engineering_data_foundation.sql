create index idx_qms_audit_tenant_object
    on qms_audit_log (tenant_id, object_type, object_id, created_at desc);
create index idx_qms_audit_tenant_actor
    on qms_audit_log (tenant_id, actor_id, created_at desc);

insert into sys_permission
    (tenant_id, permission_code, permission_name, resource_type, module_code, action_code,
     created_by, created_at, updated_by, updated_at, deleted, version)
select t.id, permission_code, permission_name, 'API', 'qms', action_code,
       0, current_timestamp, 0, current_timestamp, false, 0
from sys_tenant t
cross join (values
    ('qms:part:view', 'View QMS parts', 'view'),
    ('qms:part:create', 'Create QMS parts', 'create'),
    ('qms:drawing:view', 'View QMS drawings', 'view'),
    ('qms:drawing:create', 'Create QMS drawings', 'create'),
    ('qms:drawing-revision:view', 'View QMS drawing revisions', 'view'),
    ('qms:drawing-revision:create', 'Create QMS drawing revisions', 'create')
) as p(permission_code, permission_name, action_code)
where not exists (
    select 1 from sys_permission existing
    where existing.tenant_id = t.id
      and existing.permission_code = p.permission_code
      and existing.deleted = false
);

insert into sys_role_permission
    (tenant_id, role_id, permission_id, created_by, created_at, updated_by, updated_at,
     deleted, version)
select r.tenant_id, r.id, p.id, 0, current_timestamp, 0, current_timestamp, false, 0
from sys_role r
join sys_permission p on p.tenant_id = r.tenant_id and p.module_code = 'qms' and p.deleted = false
where r.role_code = 'platform_admin'
  and r.deleted = false
  and not exists (
      select 1 from sys_role_permission rp
      where rp.tenant_id = r.tenant_id
        and rp.role_id = r.id
        and rp.permission_id = p.id
        and rp.deleted = false
  );
