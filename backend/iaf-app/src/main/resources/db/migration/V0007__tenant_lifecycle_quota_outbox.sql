alter table sys_tenant
    add column if not exists disabled_at timestamp,
    add column if not exists initialization_status varchar(32) not null default 'COMPLETED',
    add column if not exists initialization_error varchar(512);

create table sys_tenant_quota (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    quota_key varchar(64) not null,
    quota_limit bigint not null,
    quota_used bigint not null default 0,
    created_by bigint,
    created_at timestamp not null default current_timestamp,
    updated_by bigint,
    updated_at timestamp not null default current_timestamp,
    deleted boolean not null default false,
    version int not null default 0,
    ext_json jsonb,
    constraint uk_sys_tenant_quota_key unique (tenant_id, quota_key)
);

create index idx_sys_tenant_quota_tenant on sys_tenant_quota (tenant_id);

create table platform_outbox_event (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    event_id varchar(64) not null,
    aggregate_type varchar(128) not null,
    aggregate_id varchar(128) not null,
    event_type varchar(128) not null,
    payload_json jsonb not null,
    status varchar(32) not null,
    retry_count int not null default 0,
    next_retry_at timestamp,
    created_by bigint,
    created_at timestamp not null default current_timestamp,
    updated_by bigint,
    updated_at timestamp not null default current_timestamp,
    deleted boolean not null default false,
    version int not null default 0,
    ext_json jsonb,
    constraint uk_platform_outbox_event_id unique (event_id)
);

create index idx_platform_outbox_tenant_status on platform_outbox_event (tenant_id, status);
create index idx_platform_outbox_event_status on platform_outbox_event (tenant_id, event_type, status);
create index idx_platform_outbox_aggregate on platform_outbox_event (tenant_id, aggregate_type, aggregate_id);

