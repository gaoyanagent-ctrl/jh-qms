insert into sys_role_permission (tenant_id, role_id, permission_id)
select 1, r.id, p.id
  from sys_role r
  join sys_permission p on p.tenant_id = r.tenant_id
 where r.tenant_id = 1
   and r.role_code = 'platform_admin'
   and p.permission_code in (
       'platform:tenant:view',
       'platform:tenant:create',
       'platform:tenant:update',
       'platform:tenant:disable',
       'platform:tenant:enable',
       'platform:tenant-quota:view',
       'platform:tenant-quota:update',
       'platform:outbox:view',
       'platform:outbox:retry'
   )
on conflict (tenant_id, role_id, permission_id) do nothing;

